"""
索引生成器：复现 GameDevMind 的三个自动生成物。

原项目由 `tools/check/generate_catalog.py` 生成 INDEX.md 与 nav/content-data.js，
由 `tools/check/generate_keywords.py` 生成 KEYWORDS.md；README 里的文档数统计
也来自同一套工具链（BEGIN GENERATED:content-stats）。

本模块用零依赖 Python 复刻：语料 -> 倒排索引 -> 三个产物 + 统计。
"""

from __future__ import annotations

import json
from collections import Counter, defaultdict
from dataclasses import dataclass
from pathlib import Path

from .corpus import DOMAIN_NAMES, Doc, load_corpus


@dataclass
class Catalog:
    docs: list[Doc]
    inverted: dict[str, list[Doc]]

    @property
    def stats(self) -> dict:
        return {
            "doc_count": len(self.docs),
            "domain_counts": dict(sorted(Counter(d.domain for d in self.docs).items())),
            "keyword_count": len(self.inverted),
            "link_count": sum(len(v) for v in self.inverted.values()),
        }


def build(corpus_dir: Path) -> Catalog:
    docs = load_corpus(corpus_dir)
    inverted: dict[str, list[Doc]] = defaultdict(list)
    for doc in docs:
        for kw in doc.keywords:
            inverted[kw.strip().lower()].append(doc)
    return Catalog(docs=docs, inverted={k: v for k, v in sorted(inverted.items())})


def _link(doc: Doc) -> str:
    return f"[{doc.title}]({doc.path})"


def render_index_md(catalog: Catalog) -> str:
    lines = [
        "# 文档索引（自动生成）",
        "",
        "> 由 `python -m gdm build` 自动生成，请勿手动编辑。",
        "> 对应原项目的 `INDEX.md`（由 `tools/check/generate_catalog.py` 生成）。",
        "",
        f"共 **{len(catalog.docs)} 篇文档**，按六大能力域分类。",
        "",
        "## 按能力域分类",
        "",
    ]
    for domain, name in DOMAIN_NAMES.items():
        group = [d for d in catalog.docs if d.domain == domain]
        if not group:
            continue
        lines.append(f"### {domain}. {name}")
        lines.append("")
        for doc in group:
            indent = "    " * min(doc.level, 2)
            lines.append(f"{indent}- {_link(doc)}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def render_keywords_md(catalog: Catalog) -> str:
    lines = [
        "# 关键词索引（自动生成）",
        "",
        "> 由 `python -m gdm build` 自动生成，请勿手动编辑。",
        "> 对应原项目的 `KEYWORDS.md`（由 `tools/check/generate_keywords.py` 生成）。",
        "",
        f"共 **{len(catalog.inverted)} 个关键词**，按术语定位文档。",
        "",
    ]
    for kw, docs in catalog.inverted.items():
        lines.append(f"### {kw}（{len(docs)} 篇）")
        lines.append("")
        lines.append(" · ".join(_link(d) for d in docs))
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def render_content_data_js(catalog: Catalog) -> str:
    """与原项目 nav/content-data.js 同款字段：t/p/c/l/r/parent。"""
    rows = [
        {
            "t": d.title,
            "p": d.path,
            "c": d.domain,
            "l": d.level,
            "r": d.roles,
            "parent": d.parent,
        }
        for d in catalog.docs
    ]
    body = ",\n".join("  " + json.dumps(row, ensure_ascii=False) for row in rows)
    kw_map = {kw: [d.path for d in docs] for kw, docs in catalog.inverted.items()}
    return (
        "// Generated by `python -m gdm build`; do not edit.\n"
        "const DOCS = [\n" + body + "\n];\n"
        "const DOMAIN_NAMES = "
        + json.dumps({str(k): v for k, v in DOMAIN_NAMES.items()}, ensure_ascii=False)
        + ";\n"
        "const KEYWORDS = " + json.dumps(kw_map, ensure_ascii=False) + ";\n"
    )


def write_outputs(catalog: Catalog, out_dir: Path) -> dict[str, Path]:
    out_dir = Path(out_dir)
    (out_dir / "nav").mkdir(parents=True, exist_ok=True)
    outputs = {
        "INDEX.md": out_dir / "INDEX.md",
        "KEYWORDS.md": out_dir / "KEYWORDS.md",
        "nav/content-data.js": out_dir / "nav" / "content-data.js",
    }
    outputs["INDEX.md"].write_text(render_index_md(catalog), encoding="utf-8")
    outputs["KEYWORDS.md"].write_text(render_keywords_md(catalog), encoding="utf-8")
    outputs["nav/content-data.js"].write_text(render_content_data_js(catalog), encoding="utf-8")
    return outputs
